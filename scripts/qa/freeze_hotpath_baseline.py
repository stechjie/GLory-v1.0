#!/usr/bin/env python3
"""Freeze the actual ad76ec05 hotspot functions for the QA-only A/B scene.

The reference subclasses inherit only unchanged infrastructure. The original
function text comes from git show, never a manually rewritten algorithm.
The sole semantic-neutral text substitution avoids inherited static-method
resolution: active_poison_layers -> _hotpath_original_poison_layers.
Run again immediately before packing to refresh current source identities.
"""
import hashlib
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
QA = ROOT / "scripts" / "qa"
COMMIT = "ad76ec05fd564201c3b27eaa2d6f3fafbfe26b9f"


def sha(value):
    return hashlib.sha256(value).hexdigest()


def original(path):
    return subprocess.check_output(["git", "show", f"{COMMIT}:{path}"], cwd=ROOT)


def method(data, name):
    text = data.decode("utf-8")
    pattern = rf"^(?:static )?func {re.escape(name)}\("
    found = re.search(pattern, text, re.M)
    if not found:
        raise RuntimeError(f"Missing original function: {name}")
    lines = text[found.start():].splitlines(keepends=True)
    kept = [lines[0]]
    for line in lines[1:]:
        if line.strip() and not line.startswith(("\t", " ", "#", "\n", "\r")):
            break
        kept.append(line)
    return "".join(kept).rstrip() + "\n"


renderer = "scenes/battle/BattleRenderer.gd"
vfx = "scenes/battle/BattleVfx.gd"
status = "scenes/battle/StatusVFXController.gd"
groups = [
    ("hotpath_baseline_vfx.gd", vfx, [
        (renderer, "_visual_id"),
        (vfx, "_collect_vfx_units"),
        (vfx, "_unit_vfx_position"),
    ]),
    ("hotpath_baseline_status.gd", status, [
        (status, "update_from_fighter"),
        (status, "active_poison_layers"),
    ]),
]
manifest = {
    "baseline_commit": COMMIT,
    "scope": "QA-only isolated script CPU hotspots; no pixel rendering, frame-rate, energy or thermal claims",
    "reference_strategy": "Exact git-show functions; shared current infrastructure; static helper renamed only",
    "shared_registry_condition": "Both arms use current UnitActorRegistry, including freed-instance validity-order fix",
    "frozen_functions": [],
    "baseline_sources": {},
    "current_sources": {},
}
for filename, parent, functions in groups:
    chunks = [
        f'extends "res://{parent}"\n',
        f"# Frozen from {COMMIT}; generated by freeze_hotpath_baseline.py.\n",
        "# QA only. Timed methods are original code, with shared unchanged infrastructure.\n",
    ]
    for path, name in functions:
        source = original(path)
        source_method = method(source, name)
        emitted = source_method
        if filename == "hotpath_baseline_status.gd":
            emitted = emitted.replace("active_poison_layers(", "_hotpath_original_poison_layers(")
        chunks.append("\n" + emitted)
        manifest["frozen_functions"].append({
            "source": path,
            "function": name,
            "original_function_sha256": sha(source_method.encode()),
            "emitted_function_sha256": sha(emitted.encode()),
            "frozen_file": f"scripts/qa/{filename}",
        })
        manifest["baseline_sources"][path] = sha(source)
    frozen = "".join(chunks)
    (QA / filename).write_text(frozen, encoding="utf-8")
    manifest["current_sources"][f"scripts/qa/{filename}"] = sha(frozen.encode())

tracked = [
    renderer, vfx, status,
    "effects/runtime/presentation/UnitActorRegistry.gd",
    "scripts/qa/FixedBattleFixture.gd",
    "scripts/battle/BattleSimulator.gd",
    "scenes/battle/BattleScreen.gd",
    "scripts/qa/ReplayDigest.gd",
    "scripts/qa/battle_hotpath_benchmark.gd",
    "project.godot",
]
for path in tracked:
    if (ROOT / path).exists():
        manifest["current_sources"][path] = sha((ROOT / path).read_bytes())
manifest["working_tree_head"] = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
body = "extends RefCounted\n# Generated source identities, refreshed before packing.\nconst DATA: Dictionary = " + json.dumps(manifest, ensure_ascii=False, indent="\t") + "\n"
(QA / "hotpath_baseline_manifest.gd").write_text(body, encoding="utf-8")
print(json.dumps({"frozen": [g[0] for g in groups], "functions": len(manifest["frozen_functions"]), "manifest": str(QA / "hotpath_baseline_manifest.gd")}))
