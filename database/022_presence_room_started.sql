-- 022: 在线状态补一列「所在房间是否已开打」（9.28bug 第 3 条，2026-09-28）
--
-- 配套设计文档：docs/交友系统设计.md（presence）、
-- database/020_room_invite.sql（邀请为什么是一条带类型的私聊）。
-- 001–021 一个字都不改 —— 编号只增不改，见 database/README.md。
--
-- ## 为什么要有这一列
--
-- 9.27 那版邀请的失效判据（scripts/multiplayer/RoomInvite.gd 的 is_expired）本来就有
-- 第 4 条「该房间的对局已经开始」，但当时**客户端拿不到这个事实** ——
-- presence 只报「在哪个房间」，不报「这间开打了没」。于是 room_started 恒传 false，
-- 需求 5 的第三种情况靠「加入时被服务端拒绝」兜底，表现为玩家点了「立即参与」
-- 才看到「连接中」。9.28 反馈第 3 条要的就是把它前移成「邀请当场显示已过时」。
--
-- 修法：让**客户端在心跳里一并自报**「我所在的房间是否已开打」（它自己知道 room phase），
-- 服务端存下来，好友列表接口把它带出去，邀请渲染时一读就有。
--
-- ## 边界与 005 完全一致：这一列也是客户端自报的
--
-- 谎报的后果只是「好友看到的邀请早/晚一点变成已过时」—— 最坏是让对方点进来时被
-- 服务端拒绝（那条兜底路径**仍然在**）。没有新增攻击面，也不会成为任何有价值判断的依据。
-- 同 presence.py 顶部那条边界：只能承载「说谎没有收益」的数据。
--
-- ## 代价表（database/README.md）
--
-- 加一列、not null + default false = 🟢（PostgreSQL 里瞬时完成，不锁表）。
-- 用 bool 而不是文本枚举：它就是个开关，没有「以后要加第三档」的迹象；
-- 而且它**不是**对外展示的档位（同 004 的可见性那种才需要枚举）。


-- ============================================================================
-- player_presence：加 room_started
-- ============================================================================

alter table player_presence
  add column room_started boolean not null default false;

comment on column player_presence.room_started is
  '客户端自报：当前所在房间的对局是否已开始（lobby 之外为 true）。仅在 room_id 非空时有意义；不在房间时写 false。与 room_id 同边界，不可作为任何有价值判断的依据。';
